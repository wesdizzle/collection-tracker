function estimateReconcileStatementWrites(stmt: string): number {
  if (/\b(?:INTO|FROM|UPDATE)\s+user_game_releases\b/i.test(stmt)) return 2;
  if (/\b(?:INTO|FROM|UPDATE)\s+games\b/i.test(stmt)) return 8;
  return 7;
}

function writeReconcileSqlChunks(
  sqlPath: string,
  sqlStatements: string[],
  maxBatchWrites: number,
): string[] {
  const executable = sqlStatements.filter((line) => {
    const trimmed = line.trim();
    return trimmed.length > 0 && !trimmed.startsWith('--');
  });
  if (executable.length === 0) return [];

  const parsed = path.parse(sqlPath);
  const chunkPaths: string[] = [];
  let currentChunk: string[] = [];
  let currentWrites = 0;
  let chunkIndex = 1;

  const flushChunk = () => {
    if (currentChunk.length === 0) return;
    const chunkPath = path.join(
      parsed.dir,
      `${parsed.name}_chunk_${String(chunkIndex).padStart(3, '0')}${parsed.ext || '.sql'}`,
    );
    const header = [
      `-- Generated by scripts/lib/reconcile_releases.ts (chunk ${chunkIndex}, estimated writes: ${currentWrites})`,
      '',
    ];
    fs.writeFileSync(
      chunkPath,
      [...header, ...currentChunk, ''].join('\n'),
      'utf8',
    );
    chunkPaths.push(chunkPath);
    chunkIndex++;
    currentChunk = [];
    currentWrites = 0;
  };

  for (const stmt of executable) {
    const cost = estimateReconcileStatementWrites(stmt);
    if (currentChunk.length > 0 && currentWrites + cost > maxBatchWrites) {
      flushChunk();
    }
    currentChunk.push(stmt);
    currentWrites += cost;
  }
  flushChunk();

  return chunkPaths;
}

/**
 * Strips common edition suffixes, subtitles, and DLC add-on phrases from titles
 * so base releases can match their canonical cartridge dumps.
 */
export function stripEditionSuffix(title: string): string {
  return title
    .replace(
      /:\s*(crewmate|definitive|deluxe|special|collector'?s?|anniversary|remastered|legacy|hd|plus|\d+th anniversary)\s*edition/gi,
      '',
    )
    .replace(
      /\s*-\s*(crewmate|definitive|deluxe|special|collector'?s?|anniversary|remastered|legacy|hd|plus)\s*edition/gi,
      '',
    )
    .replace(
      /\s+(definitive|deluxe|special|collector'?s?|anniversary|remastered|legacy)\s+edition/gi,
      '',
    )
    .replace(/:\s*deluxe$/i, '')
    .replace(/\s*\+\s*the hidden treasure of area zero/gi, '')
    .replace(/\s*\+\s*booster course pass/gi, '')
    .trim();
}

/**
 * Selects the best candidate canonical release based on strict regional compatibility.
 * Returns null when no candidate is regionally compatible with targetRegion (preventing
 * cross-region fallback mismatches like assigning Japan or Germany ROMs to USA rows).
 */
export function selectBestRegionalCandidate<
  T extends { region: string | null },
>(candidates: T[], targetRegion: string | null): T | null {
  if (candidates.length === 0) {
    return null;
  }
  if (!targetRegion || !targetRegion.trim()) {
    return candidates[0];
  }

  const regLower = targetRegion.toLowerCase().trim();
  const targetTokens = regLower
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean);

  // 1. Exact match (case-insensitive)
  const exact = candidates.find(
    (c) => c.region && c.region.toLowerCase().trim() === regLower,
  );
  if (exact) return exact;

  // 2. Direct token overlap (e.g. target "USA" matches candidate "USA, Europe" or "USA, Canada")
  const tokenMatch = candidates.find((c) => {
    if (!c.region) return false;
    const candTokens = c.region
      .toLowerCase()
      .split(',')
      .map((s) => s.trim())
      .filter(Boolean);
    return candTokens.some((t) => targetTokens.includes(t));
  });
  if (tokenMatch) return tokenMatch;

  // 3. World fallback (if candidate is World or target is World)
  if (targetTokens.includes('world')) {
    return candidates[0];
  }
  const anyWorld = candidates.find((c) => {
    if (!c.region) return false;
    const candTokens = c.region
      .toLowerCase()
      .split(',')
      .map((s) => s.trim());
    return candTokens.includes('world');
  });
  if (anyWorld) return anyWorld;

  // 4. North America -> USA / Canada compatibility
  if (targetTokens.includes('north america') || targetTokens.includes('usa')) {
    const naMatch = candidates.find((c) => {
      if (!c.region) return false;
      const candLower = c.region.toLowerCase();
      return candLower.includes('usa') || candLower.includes('north america');
    });
    if (naMatch) return naMatch;
  }

  return null;
}

const ROM_EXTENSION_RE =
  /\.(?:iso|bin|cue|chd|rvz|gcz|wbfs|xci|nsp|nsz|cia|3ds|nds|dsi|gba|gbc|gb|n64|z64|v64|sfc|smc|fig|swc|nes|fds|unf|md|gen|smd|sms|gg|32x|pce|ngp|ngc|ws|wsc|zip|7z|rar|cso|pbp|pkg|vpk|wua|wux|wud|dol|gcm|cdi|gdi|mdf|mds|img|ccd|sub|nrg|lnx|a26|a52|a78|j64|jag|col|int|vec|vb)$/i;

function escapeSqlValue(s: string | null | undefined): string {
  return s !== null && s !== undefined ? `'${s.replace(/'/g, "''")}'` : 'NULL';
}

function extractCleanRomTitle(rawTitleOrRomName: string): string {
  const withoutExt = rawTitleOrRomName.replace(ROM_EXTENSION_RE, '').trim();
  return withoutExt
    .replace(/\s*[[(][^\])\r\n]+[\])]\s*/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

export interface GameRomValidationTarget {
  title: string;
  platform_id: number;
  metadata_json?: string | null;
  bundle_parent_id?: number | null;
}

export interface CandidateRomValidationInput {
  raw_title?: string | null;
  rom_name?: string | null;
  region?: string | null;
  also_released_as?: string | null;
}

function parseMetadataAlternatives(
  metadataJson: string | null | undefined,
  alsoReleasedAs: string | null | undefined,
): Array<{ name: string; comment?: string }> {
  const alts: Array<{ name: string; comment?: string }> = [];
  if (metadataJson) {
    try {
      const parsed = JSON.parse(metadataJson) as {
        alternative_names?: Array<{ name?: string; comment?: string } | string>;
        game_localizations?: Array<
          { name?: string; region?: { name?: string } | string } | string
        >;
      };
      if (Array.isArray(parsed.alternative_names)) {
        for (const alt of parsed.alternative_names) {
          if (typeof alt === 'string') {
            if (alt.trim()) alts.push({ name: alt.trim() });
          } else if (alt && typeof alt.name === 'string' && alt.name.trim()) {
            alts.push({ name: alt.name.trim(), comment: alt.comment });
          }
        }
      }
      if (Array.isArray(parsed.game_localizations)) {
        for (const loc of parsed.game_localizations) {
          if (typeof loc === 'string') {
            if (loc.trim()) alts.push({ name: loc.trim() });
          } else if (loc && typeof loc.name === 'string' && loc.name.trim()) {
            const regionComment =
              typeof loc.region === 'string'
                ? loc.region
                : loc.region && typeof loc.region.name === 'string'
                  ? loc.region.name
                  : undefined;
            alts.push({ name: loc.name.trim(), comment: regionComment });
          }
        }
      }
    } catch {
      // Ignore malformed JSON metadata
    }
  }
  if (alsoReleasedAs) {
    for (const part of alsoReleasedAs.split(/[,;/|]+/)) {
      const trimmed = part.trim();
      if (trimmed) {
        alts.push({ name: trimmed });
      }
    }
  }
  return alts;
}

/**
 * Validates whether a ROM / canonical release candidate legitimately matches
 * the target game, accounting for compilations, edition suffixes, and localized
 * IGDB alternative/also-released-as names.
 */
export function isRomValidForGame(
  game: GameRomValidationTarget,
  candidate: CandidateRomValidationInput,
): boolean {
  const rawInput = (candidate.raw_title || candidate.rom_name || '').trim();
  if (!rawInput) return false;

  if (
    game.bundle_parent_id != null ||
    isCompilationOrBundleTitle(game.title) ||
    isCompilationOrBundleTitle(rawInput)
  ) {
    return true;
  }

  const releaseTitle = extractCleanRomTitle(rawInput) || rawInput;
  const rawReleaseName = (candidate.rom_name || candidate.raw_title || '')
    .replace(ROM_EXTENSION_RE, '')
    .trim();
  const alternativeNames = parseMetadataAlternatives(
    game.metadata_json,
    candidate.also_released_as,
  );

  if (
    gameMatchesReleaseWithAlternatives(
      game.title,
      releaseTitle,
      rawReleaseName,
      game.platform_id,
      alternativeNames,
      candidate.region,
    )
  ) {
    return true;
  }

  const strippedGameTitle = stripEditionSuffix(game.title);
  if (
    strippedGameTitle &&
    strippedGameTitle !== game.title &&
    gameMatchesReleaseWithAlternatives(
      strippedGameTitle,
      releaseTitle,
      rawReleaseName,
      game.platform_id,
      alternativeNames,
      candidate.region,
    )
  ) {
    return true;
  }

  const strippedReleaseTitle = stripEditionSuffix(releaseTitle);
  if (
    strippedReleaseTitle &&
    strippedReleaseTitle !== releaseTitle &&
    gameMatchesReleaseWithAlternatives(
      game.title,
      strippedReleaseTitle,
      rawReleaseName,
      game.platform_id,
      alternativeNames,
      candidate.region,
    )
  ) {
    return true;
  }

  return false;
}

