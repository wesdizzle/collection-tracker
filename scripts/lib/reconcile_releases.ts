const ENGLISH_REGION_TOKENS = new Set([
  'usa',
  'canada',
  'world',
  'uk',
  'australia',
  'north america',
]);

function isEnglishRegionValue(region: string | null | undefined): boolean {
  if (!region || !region.trim()) return true;
  const tokens = region
    .toLowerCase()
    .split(',')
    .map((t) => t.trim())
    .filter(Boolean);
  return tokens.length > 0 && tokens.every((t) => ENGLISH_REGION_TOKENS.has(t));
}

const NON_ENGLISH_ROM_TAG_RE =
  /\((?:Japan|Germany|France|Spain|Italy|Korea|China|Asia|Russia)\)/i;

const AUDIT_EXTRA_BUNDLE_TITLE_RE = /\b(?:action\s+pack|bundle|saga)\b/i;
const SHARED_EDITION_DISC_RE =
  /[:\-–]?\s*(?:game of the year edition|goty edition|gold edition|gourmet edition|next level edition|ultimate edition|treasure trove|connected)\b/gi;

function isLegitimateSharedEditionDisc(
  gameTitle: string,
  romName: string | null | undefined,
): boolean {
  if (!romName) return false;
  if (/\((?:Bonus Disc|Tokusei Disc|Kakuchou Disc)\)/i.test(romName)) {
    return false;
  }
  const romClean = extractCleanRomTitle(romName);
  SHARED_EDITION_DISC_RE.lastIndex = 0;
  const gameHasEd = SHARED_EDITION_DISC_RE.test(gameTitle);
  SHARED_EDITION_DISC_RE.lastIndex = 0;
  const romHasEd = SHARED_EDITION_DISC_RE.test(romClean);
  if (!gameHasEd && !romHasEd) return false;
  const strippedGame = gameTitle.replace(SHARED_EDITION_DISC_RE, '').trim();
  const strippedRom = romClean.replace(SHARED_EDITION_DISC_RE, '').trim();
  return Boolean(
    strippedGame &&
    strippedRom &&
    normalizeTitleForMatching(strippedGame) ===
      normalizeTitleForMatching(strippedRom),
  );
}

/**
 * Audits populated non-compilation game_releases rows against their parent games
 * for cross-IGDB ROM CRC collisions and mismatched wrong-game ROMs, then emits
 * primary-key indexed SQL repairs (re-matching canonical_releases or clearing bad ROMs).
 */
export function auditAndRepairCorruptedRoms(
  db: Database.Database,
  options: CorruptedRomAuditOptions = {},
): CorruptedRomAuditResult {
  const isDryRun = options.dryRun ?? false;
  const gamesCols = new Set(
    (db.pragma('table_info(games)') as Array<{ name: string }>).map(
      (c) => c.name,
    ),
  );
  const grCols = new Set(
    (db.pragma('table_info(game_releases)') as Array<{ name: string }>).map(
      (c) => c.name,
    ),
  );
  const crCols = new Set(
    (
      db.pragma('table_info(canonical_releases)') as Array<{ name: string }>
    ).map((c) => c.name),
  );

  const hasGameIgdbId = gamesCols.has('igdb_id');
  const hasGameMeta = gamesCols.has('metadata_json');
  const hasGameBundle = gamesCols.has('bundle_parent_id');
  const hasGrAlso = grCols.has('also_released_as');
  const hasGrDenormalized = grCols.has('verified_source');
  const hasCrVerified = crCols.has('is_verified_physical');
  const hasCrAlso = crCols.has('also_released_as');
  const hasCrSource = crCols.has('source');
  const hasCrSerial = crCols.has('serial_code');
  const hasCrPublisher = crCols.has('publisher');

  const platformFilter =
    options.platformId !== undefined
      ? ` AND g.platform_id = ${Number(options.platformId)}`
      : '';

  const populatedRows = db
    .prepare(
      `SELECT gr.id AS release_id,
              gr.game_id,
              gr.region,
              gr.rom_name,
              gr.rom_crc,
              gr.canonical_release_id,
              ${hasGrAlso ? 'gr.also_released_as' : 'NULL AS also_released_as'},
              g.platform_id,
              g.title AS game_title,
              ${hasGameIgdbId ? 'g.igdb_id' : 'NULL AS igdb_id'},
              ${hasGameMeta ? 'g.metadata_json' : 'NULL AS metadata_json'},
              ${hasGameBundle ? 'g.bundle_parent_id' : 'NULL AS bundle_parent_id'},
              cr.raw_title AS cr_raw_title,
              ${hasCrAlso ? 'cr.also_released_as' : 'NULL AS cr_also_released_as'}
       FROM game_releases gr
       JOIN games g ON g.stable_id = gr.game_id
       LEFT JOIN canonical_releases cr ON cr.id = gr.canonical_release_id
       WHERE (gr.rom_name IS NOT NULL OR (gr.rom_crc IS NOT NULL AND gr.rom_crc != ''))
         ${platformFilter}
       ORDER BY gr.game_id ASC, gr.id ASC`,
    )
    .all() as Array<{
    release_id: string;
    game_id: number;
    region: string | null;
    rom_name: string | null;
    rom_crc: string | null;
    canonical_release_id: number | null;
    also_released_as: string | null;
    platform_id: number;
    game_title: string;
    igdb_id: number | null;
    metadata_json: string | null;
    bundle_parent_id: number | null;
    cr_raw_title: string | null;
    cr_also_released_as: string | null;
  }>;

  // Build per-game existing canonical/CRC sets and per-platform game lists for Rule 2
  const usedCanonicalIdsByGame = new Map<number, Set<number>>();
  const usedCrcsByGame = new Map<number, Set<string>>();
  for (const row of populatedRows) {
    if (row.canonical_release_id != null) {
      let set = usedCanonicalIdsByGame.get(row.game_id);
      if (!set) {
        set = new Set<number>();
        usedCanonicalIdsByGame.set(row.game_id, set);
      }
      set.add(row.canonical_release_id);
    }
    const crcLower = (row.rom_crc || '').trim().toLowerCase();
    if (crcLower) {
      let crcSet = usedCrcsByGame.get(row.game_id);
      if (!crcSet) {
        crcSet = new Set<string>();
        usedCrcsByGame.set(row.game_id, crcSet);
      }
      crcSet.add(crcLower);
    }
  }

  const allGames = db
    .prepare(
      `SELECT stable_id, title, platform_id,
              ${hasGameIgdbId ? 'igdb_id' : 'NULL AS igdb_id'}
       FROM games
       ${options.platformId !== undefined ? 'WHERE platform_id = ' + Number(options.platformId) : ''}`,
    )
    .all() as Array<{
    stable_id: number;
    title: string;
    platform_id: number;
    igdb_id: number | null;
  }>;

  const gamesByPlatform = new Map<number, typeof allGames>();
  for (const g of allGames) {
    let list = gamesByPlatform.get(g.platform_id);
    if (!list) {
      list = [];
      gamesByPlatform.set(g.platform_id, list);
    }
    list.push(g);
  }

  const isRowCompilation = (row: (typeof populatedRows)[number]): boolean => {
    const rawRom = (row.cr_raw_title || row.rom_name || '').trim();
    return (
      row.bundle_parent_id != null ||
      isCompilationOrBundleTitle(row.game_title) ||
      AUDIT_EXTRA_BUNDLE_TITLE_RE.test(row.game_title) ||
      (rawRom !== '' && isCompilationOrBundleTitle(rawRom)) ||
      (row.rom_name ? /\(Demo\)/i.test(row.rom_name) : false) ||
      isLegitimateSharedEditionDisc(row.game_title, row.rom_name)
    );
  };

  const rowCandidate = (
    row: (typeof populatedRows)[number],
  ): CandidateRomValidationInput => ({
    raw_title: row.cr_raw_title || row.rom_name,
    rom_name: row.rom_name,
    region: row.region,
    also_released_as: row.cr_also_released_as || row.also_released_as,
  });

  const rowGameTarget = (
    row: (typeof populatedRows)[number],
  ): GameRomValidationTarget => ({
    title: row.game_title,
    platform_id: row.platform_id,
    metadata_json: row.metadata_json,
    bundle_parent_id: row.bundle_parent_id,
  });

  const flaggedReasonByReleaseId = new Map<string, CorruptedRomReason>();
  const rowByReleaseId = new Map<string, (typeof populatedRows)[number]>();
  for (const row of populatedRows) {
    rowByReleaseId.set(row.release_id, row);
  }

  // Rule 1: cross-IGDB (platform_id, LOWER(rom_crc)) collision on non-compilations
  const nonCompByPlatformCrc = new Map<
    string,
    Array<(typeof populatedRows)[number]>
  >();
  for (const row of populatedRows) {
    const crcLower = (row.rom_crc || '').trim().toLowerCase();
    if (!crcLower || isRowCompilation(row)) continue;
    const key = `${row.platform_id}::${crcLower}`;
    let group = nonCompByPlatformCrc.get(key);
    if (!group) {
      group = [];
      nonCompByPlatformCrc.set(key, group);
    }
    group.push(row);
  }

  for (const group of nonCompByPlatformCrc.values()) {
    const distinctIgdbIds = new Set(
      group
        .map((r) => r.igdb_id)
        .filter((id): id is number => id != null && id > 0),
    );
    if (distinctIgdbIds.size < 2) continue;

    const hasValidHolder = group.some((r) =>
      isRomValidForGame(rowGameTarget(r), rowCandidate(r)),
    );
    if (!hasValidHolder) continue;

    for (const r of group) {
      if (!isRomValidForGame(rowGameTarget(r), rowCandidate(r))) {
        flaggedReasonByReleaseId.set(r.release_id, 'cross_igdb_crc_collision');
      }
    }
  }

  // Rule 2: LEGO brand mismatch or English wrong-game ROM matching another IGDB game
  for (const row of populatedRows) {
    if (flaggedReasonByReleaseId.has(row.release_id)) continue;
    if (!row.rom_name || isRowCompilation(row)) continue;
    if (isRomValidForGame(rowGameTarget(row), rowCandidate(row))) continue;

    const romTitle = extractCleanRomTitle(row.rom_name);
    if (!romTitle) continue;

    const gameHasLego = /\blego\b/i.test(row.game_title);
    const romHasLego = /\blego\b/i.test(romTitle);
    if (gameHasLego !== romHasLego) {
      flaggedReasonByReleaseId.set(row.release_id, 'lego_brand_mismatch');
      continue;
    }

    const rawRomName = row.rom_name;
    if (
      isEnglishRegionValue(row.region) &&
      !NON_ENGLISH_ROM_TAG_RE.test(rawRomName)
    ) {
      const platformGames = gamesByPlatform.get(row.platform_id) || [];
      const matchesOtherGame = platformGames.some(
        (other) =>
          other.stable_id !== row.game_id &&
          other.igdb_id != null &&
          other.igdb_id !== row.igdb_id &&
          titlesMatch(other.title, romTitle, rawRomName, row.platform_id),
      );
      if (matchesOtherGame) {
        flaggedReasonByReleaseId.set(row.release_id, 'english_wrong_game_rom');
      }
    }
  }

  const findCanonicalStmt = db.prepare(
    `SELECT id, raw_title, region, rom_name, rom_crc,
            ${hasCrAlso ? 'also_released_as' : 'NULL AS also_released_as'},
            ${hasCrSource ? 'source' : "'dat' AS source"},
            ${hasCrSerial ? 'serial_code' : 'NULL AS serial_code'},
            ${hasCrPublisher ? 'publisher' : 'NULL AS publisher'}
     FROM canonical_releases
     WHERE platform_id = ?
       AND normalized_title IN (?, ?)
       ${hasCrVerified ? 'AND is_verified_physical = 1' : ''}
       AND rom_name IS NOT NULL`,
  );

  const flagged: CorruptedRomAuditItem[] = [];
  const sqlStatements: string[] = [];
  const countsByReason: Record<CorruptedRomReason, number> = {
    cross_igdb_crc_collision: 0,
    lego_brand_mismatch: 0,
    english_wrong_game_rom: 0,
  };
  let repairedCount = 0;
  let clearedCount = 0;

  for (const [releaseId, reason] of flaggedReasonByReleaseId) {
    const row = rowByReleaseId.get(releaseId)!;
    countsByReason[reason]++;

    const normFull = normalizeTitleForMatching(row.game_title);
    const normStripped = normalizeTitleForMatching(
      stripEditionSuffix(row.game_title),
    );
    const candidates = findCanonicalStmt.all(
      row.platform_id,
      normFull,
      normStripped || normFull,
    ) as Array<{
      id: number;
      raw_title: string;
      region: string | null;
      rom_name: string | null;
      rom_crc: string | null;
      also_released_as: string | null;
      source: string | null;
      serial_code: string | null;
      publisher: string | null;
    }>;

    const usedCanonIds = usedCanonicalIdsByGame.get(row.game_id);
    const usedCrcs = usedCrcsByGame.get(row.game_id);
    const currentCrcLower = (row.rom_crc || '').trim().toLowerCase();

    const validCandidates = candidates.filter((cand) => {
      if (!cand.rom_name) return false;
      if (cand.id !== row.canonical_release_id && usedCanonIds?.has(cand.id)) {
        return false;
      }
      const candCrcLower = (cand.rom_crc || '').trim().toLowerCase();
      if (
        candCrcLower &&
        candCrcLower !== currentCrcLower &&
        usedCrcs?.has(candCrcLower)
      ) {
        return false;
      }
      return isRomValidForGame(rowGameTarget(row), {
        raw_title: cand.raw_title,
        rom_name: cand.rom_name,
        region: cand.region,
        also_released_as: cand.also_released_as,
      });
    });

    const best = selectBestRegionalCandidate(validCandidates, row.region);
    if (best && best.rom_name) {
      repairedCount++;
      usedCanonIds?.add(best.id);
      if (best.rom_crc) {
        usedCrcs?.add(best.rom_crc.trim().toLowerCase());
      }
      flagged.push({
        releaseId: row.release_id,
        gameId: row.game_id,
        platformId: row.platform_id,
        gameTitle: row.game_title,
        igdbId: row.igdb_id,
        region: row.region,
        oldCanonicalReleaseId: row.canonical_release_id,
        oldRomName: row.rom_name,
        oldRomCrc: row.rom_crc,
        reason,
        action: 'repaired',
        newCanonicalReleaseId: best.id,
        newRomName: best.rom_name,
        newRomCrc: best.rom_crc,
        newVerifiedSource: best.source || 'dat',
        newSerialCode: best.serial_code ?? null,
        newCanonicalTitle: best.raw_title,
        newPublisher: best.publisher ?? null,
      });
      if (hasGrDenormalized) {
        sqlStatements.push(
          `UPDATE game_releases SET canonical_release_id = ${best.id}, rom_name = ${escapeSqlValue(best.rom_name)}, rom_crc = ${escapeSqlValue(best.rom_crc)}, verified_source = ${escapeSqlValue(best.source || 'dat')}, serial_code = ${escapeSqlValue(best.serial_code ?? null)}, canonical_title = ${escapeSqlValue(best.raw_title)}, publisher = ${escapeSqlValue(best.publisher ?? null)} WHERE id = ${escapeSqlValue(row.release_id)};`,
        );
      } else {
        sqlStatements.push(
          `UPDATE game_releases SET canonical_release_id = ${best.id}, rom_name = ${escapeSqlValue(best.rom_name)}, rom_crc = ${escapeSqlValue(best.rom_crc)} WHERE id = ${escapeSqlValue(row.release_id)};`,
        );
      }
    } else {
      clearedCount++;
      flagged.push({
        releaseId: row.release_id,
        gameId: row.game_id,
        platformId: row.platform_id,
        gameTitle: row.game_title,
        igdbId: row.igdb_id,
        region: row.region,
        oldCanonicalReleaseId: row.canonical_release_id,
        oldRomName: row.rom_name,
        oldRomCrc: row.rom_crc,
        reason,
        action: 'cleared',
        newCanonicalReleaseId: null,
        newRomName: null,
        newRomCrc: null,
        newVerifiedSource: null,
        newSerialCode: null,
        newCanonicalTitle: null,
        newPublisher: null,
      });
      if (hasGrDenormalized) {
        sqlStatements.push(
          `UPDATE game_releases SET canonical_release_id = NULL, rom_name = NULL, rom_crc = NULL, verified_source = NULL, serial_code = NULL, canonical_title = NULL, publisher = NULL WHERE id = ${escapeSqlValue(row.release_id)};`,
        );
      } else {
        sqlStatements.push(
          `UPDATE game_releases SET canonical_release_id = NULL, rom_name = NULL, rom_crc = NULL WHERE id = ${escapeSqlValue(row.release_id)};`,
        );
      }
    }
  }

  if (flagged.length > 0) {
    sqlStatements.push(
      "INSERT INTO sync_state (key, value) VALUES ('db_dirty', '1') ON CONFLICT(key) DO UPDATE SET value = '1';",
    );
  }

  if (!isDryRun && flagged.length > 0) {
    const repairStmt = hasGrDenormalized
      ? db.prepare(
          'UPDATE game_releases SET canonical_release_id = ?, rom_name = ?, rom_crc = ?, verified_source = ?, serial_code = ?, canonical_title = ?, publisher = ? WHERE id = ?',
        )
      : db.prepare(
          'UPDATE game_releases SET canonical_release_id = ?, rom_name = ?, rom_crc = ? WHERE id = ?',
        );
    const clearStmt = hasGrDenormalized
      ? db.prepare(
          'UPDATE game_releases SET canonical_release_id = NULL, rom_name = NULL, rom_crc = NULL, verified_source = NULL, serial_code = NULL, canonical_title = NULL, publisher = NULL WHERE id = ?',
        )
      : db.prepare(
          'UPDATE game_releases SET canonical_release_id = NULL, rom_name = NULL, rom_crc = NULL WHERE id = ?',
        );
    const tx = db.transaction(() => {
      for (const item of flagged) {
        if (item.action === 'repaired') {
          if (hasGrDenormalized) {
            repairStmt.run(
              item.newCanonicalReleaseId,
              item.newRomName,
              item.newRomCrc,
              item.newVerifiedSource ?? 'dat',
              item.newSerialCode ?? null,
              item.newCanonicalTitle ?? null,
              item.newPublisher ?? null,
              item.releaseId,
            );
          } else {
            repairStmt.run(
              item.newCanonicalReleaseId,
              item.newRomName,
              item.newRomCrc,
              item.releaseId,
            );
          }
        } else {
          clearStmt.run(item.releaseId);
        }
      }
    });
    tx();
  }

  if (options.sqlOutputPath) {
    const dir = path.dirname(options.sqlOutputPath);
    if (!fs.existsSync(dir)) {
      fs.mkdirSync(dir, { recursive: true });
    }
    fs.writeFileSync(
      options.sqlOutputPath,
      sqlStatements.join('\n') + (sqlStatements.length > 0 ? '\n' : ''),
      'utf8',
    );
  }

  return {
    flagged,
    repairedCount,
    clearedCount,
    countsByReason,
    sqlStatements,
  };
}

/**
 * Reconciles unlinked game_releases with canonical DAT releases.
 */
export function reconcileGameReleasesWithCanonical(
  db: Database.Database,
  options: ReconcileOptions = {},
): ReconcileResult {
  const isDryRun = options.dryRun ?? false;
  const sqlPath =
    options.sqlOutputPath ??
    path.resolve(
      process.cwd(),
      'scripts',
      'temp',
      'reconcile_game_releases.sql',
    );
  fs.mkdirSync(path.dirname(sqlPath), { recursive: true });

  const relinkSqlStatements: string[] = [];
  const escapeSqlGlobal = (s: string | null | undefined) =>
    s !== null && s !== undefined ? `'${s.replace(/'/g, "''")}'` : 'NULL';

  // Sync existing game_releases metadata (canonical_release_id, rom_name, rom_crc, also_released_as, variants) from canonical_releases
  try {
    const grTableInfoPre = db.pragma('table_info(game_releases)') as Array<{
      name: string;
    }>;
    const hasGrAlsoPre = grTableInfoPre.some(
      (c) => c.name === 'also_released_as',
    );
    const hasGrDenormPre = grTableInfoPre.some(
      (c) => c.name === 'verified_source',
    );
    const crTableInfoPre = db.pragma(
      'table_info(canonical_releases)',
    ) as Array<{
      name: string;
    }>;
    const hasCrAlsoPre = crTableInfoPre.some(
      (c) => c.name === 'also_released_as',
    );
    const hasCrSourcePre = crTableInfoPre.some((c) => c.name === 'source');
    const hasCrSerialPre = crTableInfoPre.some((c) => c.name === 'serial_code');
    const hasCrPublisherPre = crTableInfoPre.some(
      (c) => c.name === 'publisher',
    );
    const selectCrAlsoPre = hasCrAlsoPre
      ? 'also_released_as'
      : 'NULL as also_released_as';
    const selectCrSourcePre = hasCrSourcePre ? 'source' : "'dat' as source";
    const selectCrSerialPre = hasCrSerialPre
      ? 'serial_code'
      : 'NULL as serial_code';
    const selectCrPublisherPre = hasCrPublisherPre
      ? 'publisher'
      : 'NULL as publisher';

    const gamesColsPre = new Set(
      (db.pragma('table_info(games)') as Array<{ name: string }>).map(
        (c) => c.name,
      ),
    );
    const selectGameMetaPre = gamesColsPre.has('metadata_json')
      ? 'g.metadata_json'
      : 'NULL as metadata_json';
    const selectGameBundlePre = gamesColsPre.has('bundle_parent_id')
      ? 'g.bundle_parent_id'
      : 'NULL as bundle_parent_id';

    const unlinkedWithRom = db
      .prepare(
        `SELECT gr.id, gr.game_id, g.platform_id, g.title, gr.region, gr.variants, gr.rom_name, gr.rom_crc,
                ${selectGameMetaPre}, ${selectGameBundlePre}
         FROM game_releases gr
         JOIN games g ON gr.game_id = g.stable_id
         WHERE gr.rom_name IS NOT NULL
           AND (gr.canonical_release_id IS NULL OR gr.canonical_release_id NOT IN (SELECT id FROM canonical_releases))
           ${options.platformId ? 'AND g.platform_id = ' + Number(options.platformId) : ''}`,
      )
      .all() as Array<{
      id: string;
      game_id: number;
      platform_id: number;
      title: string;
      region: string | null;
      variants: string | null;
      rom_name: string;
      rom_crc: string | null;
      metadata_json: string | null;
      bundle_parent_id: number | null;
    }>;

    if (unlinkedWithRom.length > 0) {
      const findByRomStmt = db.prepare(
        `SELECT id, raw_title, region, rom_name, rom_crc, variants, ${selectCrAlsoPre}, ${selectCrSourcePre}, ${selectCrSerialPre}, ${selectCrPublisherPre} FROM canonical_releases WHERE platform_id = ? AND rom_name = ? LIMIT 1`,
      );
      const findByCrcStmt = db.prepare(
        `SELECT id, raw_title, region, rom_name, rom_crc, variants, ${selectCrAlsoPre}, ${selectCrSourcePre}, ${selectCrSerialPre}, ${selectCrPublisherPre} FROM canonical_releases WHERE platform_id = ? AND LOWER(rom_crc) = LOWER(?) LIMIT 1`,
      );
      const isCanonicalUsedOnGameStmt = db.prepare(
        `SELECT 1 FROM game_releases WHERE game_id = ? AND canonical_release_id = ? AND id != ? LIMIT 1`,
      );

      for (const gr of unlinkedWithRom) {
        let match = findByRomStmt.get(gr.platform_id, gr.rom_name) as
          | {
              id: number;
              raw_title: string | null;
              region: string | null;
              rom_name: string;
              rom_crc: string | null;
              variants: string | null;
              also_released_as: string | null;
              source: string | null;
              serial_code: string | null;
              publisher: string | null;
            }
          | undefined;

        if (!match && gr.rom_crc) {
          match = findByCrcStmt.get(gr.platform_id, gr.rom_crc) as
            | typeof match
            | undefined;
        }

        if (
          match &&
          !isCanonicalUsedOnGameStmt.get(gr.game_id, match.id, gr.id) &&
          isRomValidForGame(
            {
              title: gr.title,
              platform_id: gr.platform_id,
              metadata_json: gr.metadata_json,
              bundle_parent_id: gr.bundle_parent_id,
            },
            {
              raw_title: match.raw_title,
              rom_name: match.rom_name,
              region: match.region || gr.region,
              also_released_as: match.also_released_as,
            },
          )
        ) {
          const matchSource = match.source || 'dat';
          if (!isDryRun) {
            if (hasGrDenormPre && hasGrAlsoPre) {
              db.prepare(
                `UPDATE game_releases
                 SET canonical_release_id = ?, rom_name = ?, rom_crc = ?,
                     variants = COALESCE(variants, ?),
                     also_released_as = COALESCE(also_released_as, ?),
                     verified_source = ?,
                     serial_code = ?,
                     canonical_title = ?,
                     publisher = ?
                 WHERE id = ?`,
              ).run(
                match.id,
                match.rom_name,
                match.rom_crc,
                match.variants,
                match.also_released_as,
                matchSource,
                match.serial_code,
                match.raw_title,
                match.publisher,
                gr.id,
              );
            } else if (hasGrAlsoPre) {
              db.prepare(
                `UPDATE game_releases
                 SET canonical_release_id = ?, rom_name = ?, rom_crc = ?,
                     variants = COALESCE(variants, ?),
                     also_released_as = COALESCE(also_released_as, ?)
                 WHERE id = ?`,
              ).run(
                match.id,
                match.rom_name,
                match.rom_crc,
                match.variants,
                match.also_released_as,
                gr.id,
              );
            } else {
              db.prepare(
                `UPDATE game_releases
                 SET canonical_release_id = ?, rom_name = ?, rom_crc = ?,
                     variants = COALESCE(variants, ?)
                 WHERE id = ?`,
              ).run(
                match.id,
                match.rom_name,
                match.rom_crc,
                match.variants,
                gr.id,
              );
            }
          }
          if (hasGrDenormPre) {
            relinkSqlStatements.push(
              `UPDATE game_releases SET canonical_release_id = (SELECT id FROM canonical_releases WHERE rom_name = ${escapeSqlGlobal(match.rom_name)} AND platform_id = ${gr.platform_id} LIMIT 1), rom_name = ${escapeSqlGlobal(match.rom_name)}, rom_crc = ${escapeSqlGlobal(match.rom_crc)}, variants = COALESCE(variants, ${escapeSqlGlobal(match.variants)}), also_released_as = COALESCE(also_released_as, ${escapeSqlGlobal(match.also_released_as)}), verified_source = ${escapeSqlGlobal(matchSource)}, serial_code = ${escapeSqlGlobal(match.serial_code)}, canonical_title = ${escapeSqlGlobal(match.raw_title)}, publisher = ${escapeSqlGlobal(match.publisher)} WHERE id = ${escapeSqlGlobal(gr.id)};`,
            );
          } else {
            relinkSqlStatements.push(
              `UPDATE game_releases SET canonical_release_id = (SELECT id FROM canonical_releases WHERE rom_name = ${escapeSqlGlobal(match.rom_name)} AND platform_id = ${gr.platform_id} LIMIT 1), rom_name = ${escapeSqlGlobal(match.rom_name)}, rom_crc = ${escapeSqlGlobal(match.rom_crc)}, variants = COALESCE(variants, ${escapeSqlGlobal(match.variants)}), also_released_as = COALESCE(also_released_as, ${escapeSqlGlobal(match.also_released_as)}) WHERE id = ${escapeSqlGlobal(gr.id)};`,
            );
          }
        }
      }
    }

    if (!isDryRun && hasGrAlsoPre && hasCrAlsoPre) {
      if (hasGrDenormPre) {
        db.prepare(
          `UPDATE game_releases
           SET also_released_as = (SELECT also_released_as FROM canonical_releases WHERE id = game_releases.canonical_release_id),
               variants = COALESCE(game_releases.variants, (SELECT variants FROM canonical_releases WHERE id = game_releases.canonical_release_id)),
               verified_source = (SELECT ${hasCrSourcePre ? 'source' : "'dat'"} FROM canonical_releases WHERE id = game_releases.canonical_release_id),
               serial_code = (SELECT ${hasCrSerialPre ? 'serial_code' : 'NULL'} FROM canonical_releases WHERE id = game_releases.canonical_release_id),
               canonical_title = (SELECT raw_title FROM canonical_releases WHERE id = game_releases.canonical_release_id),
               publisher = (SELECT ${hasCrPublisherPre ? 'publisher' : 'NULL'} FROM canonical_releases WHERE id = game_releases.canonical_release_id)
           WHERE canonical_release_id IS NOT NULL`,
        ).run();
      } else {
        db.prepare(
          `UPDATE game_releases
           SET also_released_as = (SELECT also_released_as FROM canonical_releases WHERE id = game_releases.canonical_release_id),
               variants = COALESCE(game_releases.variants, (SELECT variants FROM canonical_releases WHERE id = game_releases.canonical_release_id))
           WHERE canonical_release_id IS NOT NULL`,
        ).run();
      }
    }
  } catch {
    // canonical_releases table may be unpopulated in test mocks
  }

  // Query releases that need ROM names
  const candidateQuery = `
    SELECT gr.id, gr.game_id, g.id as game_slug, g.platform_id, g.title, gr.region, gr.variants,
           gr.rom_name, gr.rom_crc, gr.canonical_release_id
    FROM game_releases gr
    JOIN games g ON gr.game_id = g.stable_id
    WHERE gr.rom_name IS NULL
    ${options.platformId ? 'AND g.platform_id = ' + Number(options.platformId) : ''}
    ORDER BY g.platform_id ASC, g.title ASC, gr.id ASC
  `;

  const candidateReleases = db.prepare(candidateQuery).all() as Array<{
    id: string;
    game_id: number;
    game_slug: string;
    platform_id: number;
    title: string;
    region: string | null;
    variants: string | null;
    rom_name: string | null;
    rom_crc: string | null;
    canonical_release_id: number | null;
  }>;

  // Track already-assigned ROM names and CRCs per game_id and per platform_id to prevent duplicate overwrites
  const usedRomsByGameId = new Map<number, Set<string>>();
  const usedRomsByPlatformId = new Map<number, Set<string>>();
  const usedCrcsByGameId = new Map<number, Set<string>>();
  const usedCrcsByPlatformId = new Map<number, Set<string>>();
  const existingReleaseIds = new Set<string>();
  const maxSeqByGameId = new Map<number, number>();
  for (const r of db
    .prepare('SELECT id, game_id FROM game_releases')
    .all() as Array<{ id: string; game_id: number }>) {
    existingReleaseIds.add(r.id);
    const match = r.id.match(new RegExp(`^${r.game_id}-(\\d+)$`));
    if (match) {
      const seq = Number(match[1]);
      if (seq > (maxSeqByGameId.get(r.game_id) ?? 0)) {
        maxSeqByGameId.set(r.game_id, seq);
      }
    }
  }
  const allocateSeqReleaseId = (gameId: number): string => {
    let seq = (maxSeqByGameId.get(gameId) ?? 0) + 1;
    while (existingReleaseIds.has(`${gameId}-${seq}`)) {
      seq++;
    }
    const nextId = `${gameId}-${seq}`;
    maxSeqByGameId.set(gameId, seq);
    existingReleaseIds.add(nextId);
    return nextId;
  };
  const existingRoms = db
    .prepare(
      `SELECT gr.game_id, g.platform_id, gr.rom_name, gr.rom_crc
       FROM game_releases gr
       JOIN games g ON gr.game_id = g.stable_id
       WHERE gr.rom_name IS NOT NULL`,
    )
    .all() as Array<{
    game_id: number;
    platform_id: number;
    rom_name: string;
    rom_crc: string | null;
  }>;
  for (const row of existingRoms) {
    let set = usedRomsByGameId.get(row.game_id);
    if (!set) {
      set = new Set();
      usedRomsByGameId.set(row.game_id, set);
    }
    set.add(row.rom_name);

    let pSet = usedRomsByPlatformId.get(row.platform_id);
    if (!pSet) {
      pSet = new Set();
      usedRomsByPlatformId.set(row.platform_id, pSet);
    }
    pSet.add(row.rom_name);

    if (row.rom_crc) {
      const crcNorm = row.rom_crc.toLowerCase();
      let cSet = usedCrcsByGameId.get(row.game_id);
      if (!cSet) {
        cSet = new Set();
        usedCrcsByGameId.set(row.game_id, cSet);
      }
      cSet.add(crcNorm);

      let pCrcSet = usedCrcsByPlatformId.get(row.platform_id);
      if (!pCrcSet) {
        pCrcSet = new Set();
        usedCrcsByPlatformId.set(row.platform_id, pCrcSet);
      }
      pCrcSet.add(crcNorm);
    }
  }

  // Map parent platform relationships (e.g. New 3DS 25 -> 3DS 23, Famicom 53 -> NES 13)
  const parentPlatformMap = new Map<number, number>();
  try {
    const platformRows = db
      .prepare(
        'SELECT id, parent_platform_id FROM platforms WHERE parent_platform_id IS NOT NULL',
      )
      .all() as Array<{ id: number; parent_platform_id: number }>;
    for (const p of platformRows) {
      parentPlatformMap.set(p.id, p.parent_platform_id);
    }
  } catch {
    // Platforms table lacks parent_platform_id column in simplified test mocks
  }

  let datPlatformFilter = '';
  if (options.platformId) {
    const pId = Number(options.platformId);
    const parentId = parentPlatformMap.get(pId);
    if (parentId) {
      datPlatformFilter = `AND platform_id IN (${pId}, ${parentId})`;
    } else {
      datPlatformFilter = `AND platform_id = ${pId}`;
    }
  }

  // Query all canonical DAT releases
  const grTableInfoMain = db.pragma('table_info(game_releases)') as Array<{
    name: string;
  }>;
  const hasGrDenormMain = grTableInfoMain.some(
    (c) => c.name === 'verified_source',
  );
  const crTableInfo = db.pragma('table_info(canonical_releases)') as Array<{
    name: string;
  }>;
  const hasCrAlso = crTableInfo.some((c) => c.name === 'also_released_as');
  const hasCrPackin = crTableInfo.some(
    (c) => c.name === 'packin_host_normalized_title',
  );
  const hasCrMainSource = crTableInfo.some((c) => c.name === 'source');
  const hasCrMainSerial = crTableInfo.some((c) => c.name === 'serial_code');
  const hasCrMainPublisher = crTableInfo.some((c) => c.name === 'publisher');
  const selectAlso = hasCrAlso
    ? 'also_released_as'
    : 'NULL as also_released_as';
  const selectPackin = hasCrPackin
    ? 'packin_host_normalized_title'
    : 'NULL as packin_host_normalized_title';
  const selectMainSource = hasCrMainSource ? 'source' : "'dat' as source";
  const selectMainSerial = hasCrMainSerial
    ? 'serial_code'
    : 'NULL as serial_code';
  const selectMainPublisher = hasCrMainPublisher
    ? 'publisher'
    : 'NULL as publisher';

  const datQuery = `
    SELECT id, platform_id, raw_title, normalized_title, region, variants, ${selectAlso}, ${selectPackin}, ${selectMainSource}, ${selectMainSerial}, ${selectMainPublisher}, rom_name, rom_crc
    FROM canonical_releases
    WHERE source = 'dat' AND rom_name IS NOT NULL
    ${datPlatformFilter}
  `;

  const allDatReleases = db.prepare(datQuery).all() as Array<{
    id: number;
    platform_id: number;
    raw_title: string;
    normalized_title: string;
    region: string | null;
    variants: string | null;
    also_released_as: string | null;
    packin_host_normalized_title: string | null;
    source: string | null;
    serial_code: string | null;
    publisher: string | null;
    rom_name: string;
    rom_crc: string | null;
  }>;

  // Group DAT releases by platform_id -> normalized_title -> list
  const datByPlatformNorm = new Map<
    number,
    Map<string, typeof allDatReleases>
  >();
  for (const r of allDatReleases) {
    if (!datByPlatformNorm.has(r.platform_id)) {
      datByPlatformNorm.set(r.platform_id, new Map());
    }
    const normMap = datByPlatformNorm.get(r.platform_id)!;
    // If packin_host_normalized_title is present, group strictly under the host game!
    const targetNormKey = r.packin_host_normalized_title || r.normalized_title;
    if (!normMap.has(targetNormKey)) {
      normMap.set(targetNormKey, []);
    }
    normMap.get(targetNormKey)!.push(r);
  }

  const updates: ReconcileResult['updates'] = [];
  const updatesByPlatform: Record<number, number> = {};
  const sqlStatements: string[] = [
    '-- Automatic Game Releases Reconciliation for Cloudflare D1',
    `-- Generated on: ${new Date().toISOString()}`,
    '',
    ...relinkSqlStatements,
  ];

  for (const rel of candidateReleases) {
    const normMap = datByPlatformNorm.get(rel.platform_id);
    const parentId = parentPlatformMap.get(rel.platform_id);
    const parentNormMap = parentId
      ? datByPlatformNorm.get(parentId)
      : undefined;

    // Helper to search a specific norm map
    const searchMap = (map?: Map<string, typeof allDatReleases>) => {
      if (!map) return undefined;
      // Strategy 1: Exact normalized title match
      const norm = normalizeTitleForMatching(rel.title);
      let cand = map.get(norm);

      // Strategy 2: Clean parentheticals
      if (!cand || cand.length === 0) {
        const clean = cleanTitleWithoutParentheticals(rel.title);
        if (clean !== rel.title) {
          cand = map.get(normalizeTitleForMatching(clean));
        }
      }

      // Strategy 3: Strip common edition suffixes
      if (!cand || cand.length === 0) {
        const stripped = stripEditionSuffix(rel.title);
        if (stripped !== rel.title) {
          cand = map.get(normalizeTitleForMatching(stripped));
        }
      }

      // Strategy 4: Subtitle prefix splitting (e.g. Job Simulator: The 2050 Archives -> Job Simulator)
      if ((!cand || cand.length === 0) && rel.title.includes(':')) {
        const prefix = rel.title.split(':')[0].trim();
        const rawCands = map.get(normalizeTitleForMatching(prefix));
        if (rawCands && rawCands.length > 0) {
          cand = rawCands.filter((c) =>
            titlesMatch(
              rel.title,
              c.raw_title,
              c.rom_name || c.raw_title,
              rel.platform_id,
            ),
          );
        }
      }

      return cand;
    };

    let candidates = searchMap(normMap);
    if ((!candidates || candidates.length === 0) && parentNormMap) {
      candidates = searchMap(parentNormMap);
    }

    if (!candidates || candidates.length === 0) continue;

    const usedSet = usedRomsByGameId.get(rel.game_id) ?? new Set<string>();
    const usedCrcSet = usedCrcsByGameId.get(rel.game_id) ?? new Set<string>();
    const availableCandidates = candidates.filter((c) => {
      if (usedSet.has(c.rom_name)) return false;
      if (c.rom_crc && usedCrcSet.has(c.rom_crc.toLowerCase())) {
        if (
          !rel.rom_crc ||
          rel.rom_crc.toLowerCase() !== c.rom_crc.toLowerCase()
        ) {
          return false;
        }
      }
      return true;
    });
    if (availableCandidates.length === 0) continue;

    // Prefer candidates matching rel.variants when present
    let variantFiltered = availableCandidates;
    if (rel.variants && rel.variants.trim()) {
      const targetVarLower = rel.variants.toLowerCase().trim();
      const exactVar = availableCandidates.filter(
        (c) => (c.variants || '').toLowerCase().trim() === targetVarLower,
      );
      if (exactVar.length > 0) {
        variantFiltered = exactVar;
      } else {
        const targetVarTokens = targetVarLower
          .split(',')
          .map((s) => s.trim())
          .filter(Boolean);
        const partialVar = availableCandidates.filter((c) => {
          const cVarLower = (c.variants || '').toLowerCase();
          return targetVarTokens.some((t) => cVarLower.includes(t));
        });
        if (partialVar.length > 0) {
          variantFiltered = partialVar;
        }
      }
    } else {
      // When rel.variants is null, prefer Standard (null variants) over special editions/demos if available
      const standardOnly = availableCandidates.filter((c) => !c.variants);
      if (standardOnly.length > 0) {
        variantFiltered = standardOnly;
      }
    }

    const best = selectBestRegionalCandidate(variantFiltered, rel.region);
    if (!best) continue;

    usedSet.add(best.rom_name);
    usedRomsByGameId.set(rel.game_id, usedSet);
    if (best.rom_crc) {
      usedCrcSet.add(best.rom_crc.toLowerCase());
      usedCrcsByGameId.set(rel.game_id, usedCrcSet);
    }

    // Keep release primary keys immutable (no CRC/slug-based ID renames)
    const newId = rel.id;
    existingReleaseIds.add(newId);

    updates.push({
      releaseId: rel.id,
      newReleaseId: newId !== rel.id ? newId : undefined,
      gameId: rel.game_id,
      gameTitle: rel.title,
      platformId: rel.platform_id,
      canonicalId: best.id,
      romName: best.rom_name,
      romCrc: best.rom_crc,
      variants: best.variants,
      alsoReleasedAs: best.also_released_as,
      verifiedSource: best.source || 'dat',
      serialCode: best.serial_code ?? null,
      canonicalTitle: best.raw_title,
      publisher: best.publisher ?? null,
    });

    updatesByPlatform[rel.platform_id] =
      (updatesByPlatform[rel.platform_id] || 0) + 1;

    const escapeSql = (s: string | null) =>
      s !== null ? `'${s.replace(/'/g, "''")}'` : 'NULL';
    const bestSource = best.source || 'dat';
    const bestDenormSetSql = hasGrDenormMain
      ? `, verified_source = ${escapeSql(bestSource)}, serial_code = ${escapeSql(best.serial_code ?? null)}, canonical_title = ${escapeSql(best.raw_title)}, publisher = ${escapeSql(best.publisher ?? null)}`
      : '';

    if (newId !== rel.id) {
      let hasUserRef = false;
      try {
        hasUserRef = Boolean(
          db
            .prepare(
              'SELECT 1 FROM user_game_releases WHERE release_id = ? LIMIT 1',
            )
            .get(rel.id),
        );
      } catch {
        // user_game_releases table may not exist in minimal test mocks
      }
      if (hasUserRef) {
        if (hasGrDenormMain) {
          sqlStatements.push(
            `INSERT OR IGNORE INTO game_releases (id, game_id, region, variants, rom_name, rom_crc, release_date, canonical_release_id, barcode, also_released_as, image_url, verified_source, serial_code, canonical_title, publisher) SELECT ${escapeSql(newId)}, game_id, region, COALESCE(variants, ${escapeSql(best.variants)}), ${escapeSql(best.rom_name)}, ${escapeSql(best.rom_crc)}, release_date, ${best.id}, barcode, COALESCE(also_released_as, ${escapeSql(best.also_released_as)}), image_url, ${escapeSql(bestSource)}, ${escapeSql(best.serial_code ?? null)}, ${escapeSql(best.raw_title)}, ${escapeSql(best.publisher ?? null)} FROM game_releases WHERE id = ${escapeSql(rel.id)};`,
          );
        } else {
          sqlStatements.push(
            `INSERT OR IGNORE INTO game_releases (id, game_id, region, variants, rom_name, rom_crc, release_date, canonical_release_id, barcode, also_released_as, image_url) SELECT ${escapeSql(newId)}, game_id, region, COALESCE(variants, ${escapeSql(best.variants)}), ${escapeSql(best.rom_name)}, ${escapeSql(best.rom_crc)}, release_date, ${best.id}, barcode, COALESCE(also_released_as, ${escapeSql(best.also_released_as)}), image_url FROM game_releases WHERE id = ${escapeSql(rel.id)};`,
          );
        }
        sqlStatements.push(
          `UPDATE user_game_releases SET release_id = ${escapeSql(newId)} WHERE release_id = ${escapeSql(rel.id)};`,
        );
        sqlStatements.push(
          `DELETE FROM game_releases WHERE id = ${escapeSql(rel.id)};`,
        );
      } else {
        sqlStatements.push(
          `UPDATE game_releases SET id = ${escapeSql(newId)}, canonical_release_id = ${best.id}, rom_name = ${escapeSql(best.rom_name)}, rom_crc = ${escapeSql(best.rom_crc)}, variants = COALESCE(variants, ${escapeSql(best.variants)}), also_released_as = COALESCE(also_released_as, ${escapeSql(best.also_released_as)})${bestDenormSetSql} WHERE id = ${escapeSql(rel.id)};`,
        );
      }
    } else {
      sqlStatements.push(
        `UPDATE game_releases SET canonical_release_id = ${best.id}, rom_name = ${escapeSql(best.rom_name)}, rom_crc = ${escapeSql(best.rom_crc)}, variants = COALESCE(variants, ${escapeSql(best.variants)}), also_released_as = COALESCE(also_released_as, ${escapeSql(best.also_released_as)})${bestDenormSetSql} WHERE id = ${escapeSql(rel.id)} AND (rom_name IS NULL OR rom_name != ${escapeSql(best.rom_name)});`,
      );
    }

    // If best is Disc 1 of a multi-disc set, automatically ensure Disc 2+ exist for this game
    const bestGroupKey = getRomGroupingKey(best.rom_name);
    if (bestGroupKey.startsWith('multi:')) {
      const siblingDiscs = availableCandidates
        .filter(
          (c) =>
            c.id !== best.id &&
            !usedSet.has(c.rom_name) &&
            c.region === best.region &&
            c.variants === best.variants &&
            getRomGroupingKey(c.rom_name) === bestGroupKey,
        )
        .sort((a, b) => a.rom_name.localeCompare(b.rom_name));

      for (const sibling of siblingDiscs) {
        usedSet.add(sibling.rom_name);
        const siblingId = allocateSeqReleaseId(rel.game_id);
        const sibSource = sibling.source || 'dat';
        if (hasGrDenormMain) {
          sqlStatements.push(
            `INSERT OR IGNORE INTO game_releases (id, game_id, canonical_release_id, region, variants, also_released_as, rom_name, rom_crc, verified_source, serial_code, canonical_title, publisher) VALUES (${escapeSql(siblingId)}, ${rel.game_id}, ${sibling.id}, ${escapeSql(sibling.region || rel.region)}, ${escapeSql(sibling.variants || rel.variants)}, ${escapeSql(sibling.also_released_as)}, ${escapeSql(sibling.rom_name)}, ${escapeSql(sibling.rom_crc)}, ${escapeSql(sibSource)}, ${escapeSql(sibling.serial_code ?? null)}, ${escapeSql(sibling.raw_title)}, ${escapeSql(sibling.publisher ?? null)});`,
          );
          if (!isDryRun) {
            db.prepare(
              `INSERT OR IGNORE INTO game_releases (id, game_id, canonical_release_id, region, variants, also_released_as, rom_name, rom_crc, verified_source, serial_code, canonical_title, publisher) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
            ).run(
              siblingId,
              rel.game_id,
              sibling.id,
              sibling.region || rel.region,
              sibling.variants || rel.variants,
              sibling.also_released_as,
              sibling.rom_name,
              sibling.rom_crc,
              sibSource,
              sibling.serial_code ?? null,
              sibling.raw_title,
              sibling.publisher ?? null,
            );
          }
        } else {
          sqlStatements.push(
            `INSERT OR IGNORE INTO game_releases (id, game_id, canonical_release_id, region, variants, also_released_as, rom_name, rom_crc) VALUES (${escapeSql(siblingId)}, ${rel.game_id}, ${sibling.id}, ${escapeSql(sibling.region || rel.region)}, ${escapeSql(sibling.variants || rel.variants)}, ${escapeSql(sibling.also_released_as)}, ${escapeSql(sibling.rom_name)}, ${escapeSql(sibling.rom_crc)});`,
          );
          if (!isDryRun) {
            db.prepare(
              `INSERT OR IGNORE INTO game_releases (id, game_id, canonical_release_id, region, variants, also_released_as, rom_name, rom_crc) VALUES (?, ?, ?, ?, ?, ?, ?, ?)`,
            ).run(
              siblingId,
              rel.game_id,
              sibling.id,
              sibling.region || rel.region,
              sibling.variants || rel.variants,
              sibling.also_released_as,
              sibling.rom_name,
              sibling.rom_crc,
            );
          }
        }
      }
    }

    // If this game hosts retail pack-in demo/bonus discs, automatically ensure they exist under this game!
    const packInDiscs = availableCandidates.filter(
      (c) => c.packin_host_normalized_title && !usedSet.has(c.rom_name),
    );
    for (const packIn of packInDiscs) {
      usedSet.add(packIn.rom_name);
      const packInId = allocateSeqReleaseId(rel.game_id);
      const packSource = packIn.source || 'dat';
      if (hasGrDenormMain) {
        sqlStatements.push(
          `INSERT OR IGNORE INTO game_releases (id, game_id, canonical_release_id, region, variants, also_released_as, rom_name, rom_crc, verified_source, serial_code, canonical_title, publisher) VALUES (${escapeSql(packInId)}, ${rel.game_id}, ${packIn.id}, ${escapeSql(packIn.region || rel.region)}, ${escapeSql(packIn.variants || 'Demo')}, ${escapeSql(packIn.also_released_as)}, ${escapeSql(packIn.rom_name)}, ${escapeSql(packIn.rom_crc)}, ${escapeSql(packSource)}, ${escapeSql(packIn.serial_code ?? null)}, ${escapeSql(packIn.raw_title)}, ${escapeSql(packIn.publisher ?? null)});`,
        );
        if (!isDryRun) {
          db.prepare(
            `INSERT OR IGNORE INTO game_releases (id, game_id, canonical_release_id, region, variants, also_released_as, rom_name, rom_crc, verified_source, serial_code, canonical_title, publisher) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
          ).run(
            packInId,
            rel.game_id,
            packIn.id,
            packIn.region || rel.region,
            packIn.variants || 'Demo',
            packIn.also_released_as,
            packIn.rom_name,
            packIn.rom_crc,
            packSource,
            packIn.serial_code ?? null,
            packIn.raw_title,
            packIn.publisher ?? null,
          );
        }
      } else {
        sqlStatements.push(
          `INSERT OR IGNORE INTO game_releases (id, game_id, canonical_release_id, region, variants, also_released_as, rom_name, rom_crc) VALUES (${escapeSql(packInId)}, ${rel.game_id}, ${packIn.id}, ${escapeSql(packIn.region || rel.region)}, ${escapeSql(packIn.variants || 'Demo')}, ${escapeSql(packIn.also_released_as)}, ${escapeSql(packIn.rom_name)}, ${escapeSql(packIn.rom_crc)});`,
        );
        if (!isDryRun) {
          db.prepare(
            `INSERT OR IGNORE INTO game_releases (id, game_id, canonical_release_id, region, variants, also_released_as, rom_name, rom_crc) VALUES (?, ?, ?, ?, ?, ?, ?, ?)`,
          ).run(
            packInId,
            rel.game_id,
            packIn.id,
            packIn.region || rel.region,
            packIn.variants || 'Demo',
            packIn.also_released_as,
            packIn.rom_name,
            packIn.rom_crc,
          );
        }
      }
    }
  }

  if (options.insertMissingVariants) {
    const escapeSql = (s: string | null) =>
      s !== null ? `'${s.replace(/'/g, "''")}'` : 'NULL';
    const catalogGames = db
      .prepare(
        `SELECT stable_id, id as slug, title, platform_id FROM games WHERE 1=1 ${options.platformId ? 'AND platform_id = ' + Number(options.platformId) : ''}`,
      )
      .all() as Array<{
      stable_id: number;
      slug: string;
      title: string;
      platform_id: number;
    }>;

    for (const g of catalogGames) {
      const normMap = datByPlatformNorm.get(g.platform_id);
      if (!normMap) continue;
      const norm = normalizeTitleForMatching(g.title);
      const cands = normMap.get(norm);
      if (!cands || cands.length === 0) continue;

      const usedSet = usedRomsByGameId.get(g.stable_id) ?? new Set<string>();
      const usedCrcSet = usedCrcsByGameId.get(g.stable_id) ?? new Set<string>();
      const platUsedSet =
        usedRomsByPlatformId.get(g.platform_id) ?? new Set<string>();
      const platUsedCrcSet =
        usedCrcsByPlatformId.get(g.platform_id) ?? new Set<string>();

      for (const c of cands) {
        if (usedSet.has(c.rom_name) || platUsedSet.has(c.rom_name)) continue;
        const crcNorm = c.rom_crc ? c.rom_crc.toLowerCase() : null;
        if (
          crcNorm &&
          (usedCrcSet.has(crcNorm) || platUsedCrcSet.has(crcNorm))
        ) {
          continue;
        }

        // Exclude re-homed box set constituent ROMs from being added onto standalone base games
        const baseNameWithoutExt = c.rom_name
          .replace(/\.(?:xiso\.iso|[a-z0-9]{2,4})$/i, '')
          .trim()
          .toLowerCase();
        if (BOX_SET_ROM_GROUPING_MAP[baseNameWithoutExt]) {
          continue;
        }

        if (
          !titlesMatch(
            g.title,
            c.raw_title,
            c.rom_name || c.raw_title,
            g.platform_id,
          )
        ) {
          continue;
        }
        usedSet.add(c.rom_name);
        usedRomsByGameId.set(g.stable_id, usedSet);
        platUsedSet.add(c.rom_name);
        usedRomsByPlatformId.set(g.platform_id, platUsedSet);
        if (crcNorm) {
          usedCrcSet.add(crcNorm);
          usedCrcsByGameId.set(g.stable_id, usedCrcSet);
          platUsedCrcSet.add(crcNorm);
          usedCrcsByPlatformId.set(g.platform_id, platUsedCrcSet);
        }
        const newId = allocateSeqReleaseId(g.stable_id);
        const candSource = c.source || 'dat';
        if (hasGrDenormMain) {
          sqlStatements.push(
            `INSERT OR IGNORE INTO game_releases (id, game_id, canonical_release_id, region, variants, also_released_as, rom_name, rom_crc, verified_source, serial_code, canonical_title, publisher) VALUES (${escapeSql(newId)}, ${g.stable_id}, ${c.id}, ${escapeSql(c.region)}, ${escapeSql(c.variants)}, ${escapeSql(c.also_released_as)}, ${escapeSql(c.rom_name)}, ${escapeSql(c.rom_crc)}, ${escapeSql(candSource)}, ${escapeSql(c.serial_code ?? null)}, ${escapeSql(c.raw_title)}, ${escapeSql(c.publisher ?? null)});`,
          );
          if (!isDryRun) {
            db.prepare(
              `INSERT OR IGNORE INTO game_releases (id, game_id, canonical_release_id, region, variants, also_released_as, rom_name, rom_crc, verified_source, serial_code, canonical_title, publisher) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
            ).run(
              newId,
              g.stable_id,
              c.id,
              c.region,
              c.variants,
              c.also_released_as,
              c.rom_name,
              c.rom_crc,
              candSource,
              c.serial_code ?? null,
              c.raw_title,
              c.publisher ?? null,
            );
          }
        } else {
          sqlStatements.push(
            `INSERT OR IGNORE INTO game_releases (id, game_id, canonical_release_id, region, variants, also_released_as, rom_name, rom_crc) VALUES (${escapeSql(newId)}, ${g.stable_id}, ${c.id}, ${escapeSql(c.region)}, ${escapeSql(c.variants)}, ${escapeSql(c.also_released_as)}, ${escapeSql(c.rom_name)}, ${escapeSql(c.rom_crc)});`,
          );
          if (!isDryRun) {
            db.prepare(
              `INSERT OR IGNORE INTO game_releases (id, game_id, canonical_release_id, region, variants, also_released_as, rom_name, rom_crc) VALUES (?, ?, ?, ?, ?, ?, ?, ?)`,
            ).run(
              newId,
              g.stable_id,
              c.id,
              c.region,
              c.variants,
              c.also_released_as,
              c.rom_name,
              c.rom_crc,
            );
          }
        }
      }
    }
  }

  sqlStatements.push('');

  // Write SQL migration file
  fs.writeFileSync(sqlPath, sqlStatements.join('\n'), 'utf8');
  const chunkSqlPaths =
    options.maxBatchWrites && options.maxBatchWrites > 0
      ? writeReconcileSqlChunks(sqlPath, sqlStatements, options.maxBatchWrites)
      : undefined;

  // Apply to local database in a transaction if not dry run
  if (!isDryRun && updates.length > 0) {
    const grTableInfo = db.pragma('table_info(game_releases)') as Array<{
      name: string;
    }>;
    const hasAlsoReleasedAs = grTableInfo.some(
      (c) => c.name === 'also_released_as',
    );
    const hasDenormalized = grTableInfo.some(
      (c) => c.name === 'verified_source',
    );

    const updateStmt =
      hasAlsoReleasedAs && hasDenormalized
        ? db.prepare(`
            UPDATE game_releases
            SET id = ?, canonical_release_id = ?, rom_name = ?, rom_crc = ?,
                variants = COALESCE(variants, ?),
                also_released_as = COALESCE(also_released_as, ?),
                verified_source = ?,
                serial_code = ?,
                canonical_title = ?,
                publisher = ?
            WHERE id = ?
          `)
        : hasAlsoReleasedAs
          ? db.prepare(`
              UPDATE game_releases
              SET id = ?, canonical_release_id = ?, rom_name = ?, rom_crc = ?,
                  variants = COALESCE(variants, ?),
                  also_released_as = COALESCE(also_released_as, ?)
              WHERE id = ?
            `)
          : db.prepare(`
              UPDATE game_releases
              SET id = ?, canonical_release_id = ?, rom_name = ?, rom_crc = ?,
                  variants = COALESCE(variants, ?)
              WHERE id = ?
            `);

    // Check if user_game_releases table exists to cascade primary key renames
    const ugrTableInfo = db.pragma('table_info(user_game_releases)') as Array<{
      name: string;
    }>;
    const cascadeUserReleaseStmt =
      ugrTableInfo.length > 0
        ? db.prepare(`
            UPDATE user_game_releases
            SET release_id = ?
            WHERE release_id = ?
          `)
        : null;

    const applyTx = db.transaction(() => {
      for (const u of updates) {
        if (hasAlsoReleasedAs && hasDenormalized) {
          updateStmt.run(
            u.newReleaseId || u.releaseId,
            u.canonicalId,
            u.romName,
            u.romCrc,
            u.variants || null,
            u.alsoReleasedAs || null,
            u.verifiedSource ?? 'dat',
            u.serialCode ?? null,
            u.canonicalTitle ?? null,
            u.publisher ?? null,
            u.releaseId,
          );
        } else if (hasAlsoReleasedAs) {
          updateStmt.run(
            u.newReleaseId || u.releaseId,
            u.canonicalId,
            u.romName,
            u.romCrc,
            u.variants || null,
            u.alsoReleasedAs || null,
            u.releaseId,
          );
        } else {
          updateStmt.run(
            u.newReleaseId || u.releaseId,
            u.canonicalId,
            u.romName,
            u.romCrc,
            u.variants || null,
            u.releaseId,
          );
        }
        if (
          cascadeUserReleaseStmt &&
          u.newReleaseId &&
          u.newReleaseId !== u.releaseId
        ) {
          cascadeUserReleaseStmt.run(u.newReleaseId, u.releaseId);
        }
      }
    });

    db.pragma('foreign_keys = OFF');
    try {
      applyTx();
    } finally {
      db.pragma('foreign_keys = ON');
    }
  }

  return {
    totalEvaluated: candidateReleases.length,
    reconciledCount: updates.length,
    updatesByPlatform,
    sqlPath,
    ...(chunkSqlPaths ? { chunkSqlPaths } : {}),
    updates,
  };
}

